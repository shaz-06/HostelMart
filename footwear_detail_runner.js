// Global active selection states
let selectedColor = "";
let selectedSize = "";
let currentAction = null;

function renderProductDetail() {
  const prod = getActiveProduct();
  if (!prod) return;

  // 1. Update document head title
  document.title = `${prod.title} | HostelMart`;

  // 2. Breadcrumbs Setup (Footwear specific)
  const navEl = document.querySelector('main > nav');
  if (navEl) {
    navEl.innerHTML = `
      <a href="index.html" class="hover:text-[#3E2723]">Home</a>
      <ion-icon name="chevron-forward-outline"></ion-icon>
      <a href="Footwear.html" class="hover:text-[#3E2723]">Footwear</a>
      <ion-icon name="chevron-forward-outline"></ion-icon>
      <a href="Footwear.html" class="hover:text-[#3E2723]">${prod.brand}</a>
      <ion-icon name="chevron-forward-outline"></ion-icon>
      <span class="text-[#3E2723] font-bold">${prod.title}</span>
    `;
  }

  // 3. Grid Images Setup
  for (let i = 0; i < 4; i++) {
    const imgEl = document.getElementById(`main-img-${i + 1}`);
    if (imgEl) {
      imgEl.src = prod.images[i] || prod.images[0];
      imgEl.alt = `${prod.title} View ${i + 1}`;
    }
  }

  // 4. Product Details Headers
  const brandEl = document.getElementById('product-brand');
  const titleEl = document.getElementById('product-title');
  if (brandEl) brandEl.textContent = prod.brand;
  if (titleEl) titleEl.textContent = prod.title;

  // 5. Ratings & Reviews
  const ratingEl = document.getElementById('product-rating');
  const ratingCountEl = document.getElementById('product-rating-count');
  if (ratingEl) ratingEl.textContent = prod.rating;
  if (ratingCountEl) ratingCountEl.textContent = prod.ratingsCount;

  // 6. Pricing Section
  const priceEl = document.getElementById('product-price');
  const originalPriceEl = document.getElementById('product-original-price');
  const discountEl = document.getElementById('product-discount');
  const buyBtnText = document.getElementById('buy-btn-price-text');
  
  if (priceEl) priceEl.textContent = `₹${prod.price}`;
  if (originalPriceEl) originalPriceEl.textContent = `₹${prod.originalPrice}`;
  if (discountEl) discountEl.textContent = prod.discount;
  if (buyBtnText) buyBtnText.textContent = `Buy at ₹${prod.price}`;

  const dealEl = document.getElementById('deal-saving-text');
  if (dealEl) {
    const dealPrice = Math.floor(prod.price * 0.90); // Custom footwear deal
    dealEl.textContent = `Buy at ₹${dealPrice}`;
  }

  // 7. Variants Color Builder
  const variantsContainer = document.getElementById('variants-container');
  if (variantsContainer) {
    selectedColor = prod.colorOptions[0].name;
    document.getElementById('color-label').textContent = selectedColor;

    variantsContainer.innerHTML = prod.colorOptions.map((opt, idx) => `
      <button onclick="updateVariant('${opt.name}')" class="variant-btn ${idx === 0 ? 'active' : ''} w-16 h-20 rounded-xl overflow-hidden border-2 border-transparent transition-all shadow-md">
        <img src="${opt.img}" class="w-full h-full object-cover">
      </button>
    `).join('');
  }

  // 8. Size Selector Builder
  const sizesContainer = document.getElementById('sizes-container');
  if (sizesContainer) {
    sizesContainer.innerHTML = prod.sizes.map(sz => `
      <button onclick="selectSize(this)" class="size-btn px-4 h-12 rounded-xl border border-[#D7CCC8] flex items-center justify-center text-xs font-black transition-all hover:border-[#3E2723]">${sz}</button>
    `).join('');
  }

  // 9. Highlights Specifications Builder
  const highlightsContainer = document.getElementById('highlights-container');
  if (highlightsContainer) {
    highlightsContainer.innerHTML = Object.entries(prod.highlights).map(([key, val]) => `
      <div class="space-y-1">
        <p class="text-[10px] font-bold text-gray-400 uppercase tracking-widest">${key}</p>
        <p class="text-xs font-black">${val}</p>
      </div>
    `).join('');
  }

  // 9.1 Dynamic Extra Sections Builder
  const extraContainer = document.getElementById('extra-sections-container');
  if (extraContainer) {
    if (prod.extraSections) {
      extraContainer.classList.remove('hidden');
      extraContainer.innerHTML = Object.entries(prod.extraSections).map(([key, val]) => `
        <div class="space-y-2 pt-6 border-t border-[#D7CCC8]/30">
          <p class="text-[10px] font-bold text-gray-400 uppercase tracking-widest">${key}</p>
          <p class="text-xs font-semibold leading-relaxed text-gray-600">${val}</p>
        </div>
      `).join('');
    } else {
      extraContainer.classList.add('hidden');
      extraContainer.innerHTML = "";
    }
  }

  // 10. Seller & Return Details
  const sellerEl = document.getElementById('seller-name');
  if (sellerEl) sellerEl.textContent = prod.seller;

  // 11. Select Variant Modal Sync
  const modalImg = document.querySelector('.variant-modal-content img');
  const modalBrand = document.querySelector('.variant-modal-content h4');
  const modalTitle = document.querySelector('.variant-modal-content p');
  const modalOriginal = document.querySelector('.variant-modal-content span.text-xs');
  const modalPrice = document.querySelector('.variant-modal-content span.text-lg');
  const modalSizesContainer = document.querySelector('.variant-modal-content .justify-between');

  if (modalImg) modalImg.src = prod.images[0];
  if (modalBrand) modalBrand.textContent = prod.brand;
  if (modalTitle) modalTitle.textContent = prod.title;
  if (modalOriginal) modalOriginal.textContent = `₹${prod.originalPrice}`;
  if (modalPrice) modalPrice.textContent = `₹${prod.price}`;
  
  if (modalSizesContainer) {
    modalSizesContainer.innerHTML = prod.sizes.map(sz => `
      <button onclick="selectSizeModal(this)" class="size-btn-modal px-3 py-2 rounded-xl border border-gray-200 flex items-center justify-center text-xs font-black transition-all hover:border-[#3E2723]">${sz}</button>
    `).join('');
  }

  // Dynamic Date calculation
  const deliveryDate = new Date();
  deliveryDate.setDate(deliveryDate.getDate() + 3); // Footwear has speedier shipping
  const dateOptions = { day: 'numeric', month: 'short', weekday: 'short' };
  const deliveryDateStr = deliveryDate.toLocaleDateString('en-IN', dateOptions);
  
  const deliveryDateEl = document.getElementById('delivery-date-estimate');
  if (deliveryDateEl) deliveryDateEl.textContent = deliveryDateStr;

  // Check if product is in cart and update button state
  const filename = window.location.pathname.split('/').pop() || 'Asian-Firefly-04.html';
  const slug = filename.replace('.html', '');
  const cart = JSON.parse(localStorage.getItem('hostelmart_cart')) || [];
  const inCart = cart.some(item => item.slug === slug || item.id === slug);
  if (inCart) {
    updateCartButtonState();
  }
}

// User Action Handlers
window.selectSize = function(btn) {
  document.querySelectorAll('.size-btn').forEach(b => b.classList.remove('active', 'bg-[#3E2723]', 'text-white'));
  btn.classList.add('active', 'bg-[#3E2723]', 'text-white');
  selectedSize = btn.innerText;
};

window.updateVariant = function(color) {
  document.querySelectorAll('.variant-btn').forEach(b => b.classList.remove('active'));
  event.currentTarget.classList.add('active');
  selectedColor = color;
  document.getElementById('color-label').innerText = color;
  
  // Dynamically swap the main preview image based on variant
  const prod = getActiveProduct();
  const matched = prod.colorOptions.find(o => o.name === color);
  if (matched) {
    const mainImg = document.getElementById('main-img-1');
    if (mainImg) mainImg.src = matched.img;
  }
};

window.handleBuyNow = function() {
  if (!selectedSize) {
    currentAction = 'buy';
    openVariantModal();
  } else {
    const prod = getActiveProduct();
    const filename = window.location.pathname.split('/').pop() || 'Asian-Firefly-04.html';
    const slug = filename.replace('.html', '');
    const data = {
      id: slug,
      slug: slug,
      img: prod.images[0],
      brand: prod.brand,
      title: prod.title,
      currentPrice: `₹${prod.price}`,
      originalPrice: `₹${prod.originalPrice}`,
      size: selectedSize,
      color: selectedColor,
      qty: 1
    };
    localStorage.setItem('checkoutItem', JSON.stringify(data));
    window.location.href = 'Checkout.html';
  }
};

window.handleAddToCart = function() {
  if (!selectedSize) {
    currentAction = 'cart';
    openVariantModal();
  } else {
    const prod = getActiveProduct();
    const filename = window.location.pathname.split('/').pop() || 'Asian-Firefly-04.html';
    const slug = filename.replace('.html', '');
    const data = {
      id: slug,
      slug: slug,
      img: prod.images[0],
      brand: prod.brand,
      title: prod.title,
      currentPrice: `₹${prod.price}`,
      originalPrice: `₹${prod.originalPrice}`,
      size: selectedSize,
      color: selectedColor,
      qty: 1
    };
    if (window.addToCart) {
      window.addToCart(data);
    }
    updateCartButtonState();
  }
};

window.confirmVariantSelection = function() {
  const selectedSizeModal = document.querySelector('.size-btn-modal.active');
  if (!selectedSizeModal) return;
  
  selectedSize = selectedSizeModal.innerText;
  
  // Reflect size on main selectors
  document.querySelectorAll('.size-btn').forEach(b => {
    if (b.innerText === selectedSize) {
      b.classList.add('active', 'bg-[#3E2723]', 'text-white');
    } else {
      b.classList.remove('active', 'bg-[#3E2723]', 'text-white');
    }
  });

  const prod = getActiveProduct();
  const filename = window.location.pathname.split('/').pop() || 'Asian-Firefly-04.html';
  const slug = filename.replace('.html', '');
  const data = {
    id: slug,
    slug: slug,
    img: prod.images[0],
    brand: prod.brand,
    title: prod.title,
    currentPrice: `₹${prod.price}`,
    originalPrice: `₹${prod.originalPrice}`,
    size: selectedSize,
    color: selectedColor,
    qty: 1
  };

  if (currentAction === 'buy') {
    localStorage.setItem('checkoutItem', JSON.stringify(data));
    window.location.href = 'Checkout.html';
  } else {
    if (window.addToCart) {
      window.addToCart(data);
    }
    updateCartButtonState();
    closeVariantModal();
  }
};

window.selectSizeModal = function(btn) {
  document.querySelectorAll('.size-btn-modal').forEach(b => b.classList.remove('active', 'bg-[#3E2723]', 'text-white'));
  btn.classList.add('active', 'bg-[#3E2723]', 'text-white');
  document.getElementById('modal-continue-btn').disabled = false;
};

window.updateCartButtonState = function() {
  const mainBtn = document.getElementById('add-to-cart-btn');
  if (mainBtn) {
    mainBtn.innerHTML = '<ion-icon name="bag-handle-outline" class="text-lg"></ion-icon> Go To Cart';
    mainBtn.onclick = () => window.location.href = 'Cart.html';
    mainBtn.classList.replace('bg-white', 'bg-[#FDFBF7]');
  }
};

window.openVariantModal = function() {
  const modal = document.getElementById('variant-modal');
  modal.classList.remove('hidden');
  document.body.style.overflow = 'hidden';
  setTimeout(() => {
    modal.classList.add('active');
  }, 10);
};

window.closeVariantModal = function() {
  const modal = document.getElementById('variant-modal');
  modal.classList.remove('active');
  setTimeout(() => {
    modal.classList.add('hidden');
    document.body.style.overflow = 'auto';
  }, 300);
};

// Premium Features: Hover Zoom Tracking
function initHoverZoom() {
  document.querySelectorAll('.image-zoom-container').forEach(container => {
    const img = container.querySelector('img');
    if (!img) return;

    container.addEventListener('mousemove', e => {
      const rect = container.getBoundingClientRect();
      const x = ((e.clientX - rect.left) / rect.width) * 100;
      const y = ((e.clientY - rect.top) / rect.height) * 100;
      img.style.transformOrigin = `${x}% ${y}%`;
      img.style.transform = 'scale(1.5)';
    });

    container.addEventListener('mouseleave', () => {
      img.style.transform = 'scale(1)';
      img.style.transformOrigin = 'center center';
    });
  });
}

