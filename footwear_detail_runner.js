window.switchLightboxImage = function(idx) {
  const activeProd = getActiveProduct();
  if (!activeProd) return;
  
  const mainImg = document.getElementById('lightbox-main-img');
  mainImg.src = activeProd.images[idx];
  
  document.querySelectorAll('.lightbox-thumb-item').forEach((item, i) => {
    if (i === idx) {
      item.classList.add('border-amber-400');
      item.classList.remove('border-transparent');
    } else {
      item.classList.add('border-transparent');
      item.classList.remove('border-amber-400');
    }
  });
};

// Map GPS Address Modal Logic
let addressMap;
let addressMarker;

window.openAddressModal = function() {
  const modal = document.getElementById('address-modal');
  const container = document.getElementById('address-container');
  
  modal.classList.remove('hidden');
  document.body.style.overflow = 'hidden';

  setTimeout(() => {
    container.classList.remove('scale-95', 'opacity-0');
    container.classList.add('scale-100', 'opacity-100');
    initAddressMap();
  }, 10);
};

window.closeAddressModal = function() {
  const container = document.getElementById('address-container');
  
  container.classList.remove('scale-100', 'opacity-100');
  container.classList.add('scale-95', 'opacity-0');

  setTimeout(() => {
    document.getElementById('address-modal').classList.add('hidden');
    document.body.style.overflow = 'auto';
  }, 500);
};

window.initAddressMap = function() {
  if (addressMap) return;

  const defaultLoc = [12.9716, 77.5946];
  addressMap = L.map('address-map').setView(defaultLoc, 13);

  L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
    attribution: '&copy; OpenStreetMap contributors'
  }).addTo(addressMap);

  addressMarker = L.marker(defaultLoc, { draggable: true }).addTo(addressMap);

  addressMarker.on('dragend', function() {
    const position = addressMarker.getLatLng();
    reverseGeocode(position.lat, position.lng);
  });

  addressMap.on('click', function(e) {
    addressMarker.setLatLng(e.latlng);
    reverseGeocode(e.latlng.lat, e.latlng.lng);
  });
};

window.useGPS = async function() {
  if (!navigator.geolocation) {
    alert("Geolocation is not supported by your browser");
    return;
  }

  const gpsBtn = event.currentTarget;
  const originalHTML = gpsBtn.innerHTML;
  gpsBtn.innerHTML = '<ion-icon name="sync-outline" class="animate-spin text-lg"></ion-icon> Locating...';

  navigator.geolocation.getCurrentPosition(
    (position) => {
      const { latitude, longitude } = position.coords;
      addressMap.setView([latitude, longitude], 16);
      addressMarker.setLatLng([latitude, longitude]);
      reverseGeocode(latitude, longitude);
      gpsBtn.innerHTML = originalHTML;
    },
    (error) => {
      alert("GPS positioning failed. Please type address manually.");
      gpsBtn.innerHTML = originalHTML;
    },
    { enableHighAccuracy: true, timeout: 10000 }
  );
};

async function reverseGeocode(lat, lng) {
  try {
    const response = await fetch(`https://nominatim.openstreetmap.org/reverse?format=jsonv2&lat=${lat}&lon=${lng}`);
    const data = await response.json();
    if (data.address) {
      const street = data.address.road || data.address.suburb || data.address.neighbourhood || '';
      const city = data.address.city || data.address.town || data.address.village || '';
      document.getElementById('manual-street').value = street;
      document.getElementById('manual-city').value = city;
    }
  } catch (err) {
    console.error("Geocoding failed", err);
  }
}

window.saveAddress = function() {
  const street = document.getElementById('manual-street').value;
  const city = document.getElementById('manual-city').value;

  if (!street || !city) {
    alert("Please enter both street and city.");
    return;
  }

  const fullAddress = `${street}, ${city}`;
  localStorage.setItem('deliveryAddress', fullAddress);
  document.getElementById('current-address').textContent = fullAddress;
  
  const confirmBtn = event.currentTarget;
  confirmBtn.innerHTML = 'Address Saved!';
  confirmBtn.classList.replace('bg-[#5D4037]', 'bg-green-600');
  
  setTimeout(() => {
    closeAddressModal();
    setTimeout(() => {
      confirmBtn.innerHTML = 'Confirm Delivery Location';
      confirmBtn.classList.replace('bg-green-600', 'bg-[#5D4037]');
    }, 1000);
  }, 800);
};

