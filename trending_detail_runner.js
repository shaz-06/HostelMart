// Premium Features: Hover Zoom Tracking
function initHoverZoom() {
  document.querySelectorAll('.image-zoom-container').forEach(container => {
    const img = container.querySelector('img');
    if (!img) return;

    container.addEventListener('mousemove', e => {
      const rect = container.getBoundingClientRect();
      const x = ((e.clientX - rect.left) / rect.width) * 100;
      const y = ((e.clientY - rect.top) / rect.height) * 100;
      img.style.transformOrigin = `${x}% ${y}%`;
      img.style.transform = 'scale(1.5)';
    });

    container.addEventListener('mouseleave', () => {
      img.style.transform = 'scale(1)';
      img.style.transformOrigin = 'center center';
    });
  });
}

// Lightbox modal with thumbnail switcher
function initLightbox() {
  const lightboxHTML = `
    <div id="lightbox-modal" class="fixed inset-0 z-[150] bg-black/95 backdrop-blur-md hidden flex items-center justify-center p-4">
      <button id="close-lightbox" class="absolute top-6 right-6 text-white text-3xl p-3 hover:bg-white/10 rounded-full transition-all">
        <ion-icon name="close-outline"></ion-icon>
      </button>
      
      <div class="flex flex-col md:flex-row items-center gap-8 max-w-5xl w-full h-[80vh] md:h-auto">
        <div class="flex md:flex-col gap-3 overflow-x-auto md:overflow-x-visible no-scrollbar max-w-full md:max-w-none flex-shrink-0" id="lightbox-thumbs">
        </div>
        <div class="flex-1 h-[50vh] md:h-[70vh] rounded-3xl overflow-hidden bg-black/40 border border-white/10 relative flex items-center justify-center">
          <img id="lightbox-main-img" src="" class="max-w-full max-h-full object-contain transition-all duration-300">
        </div>
      </div>
    </div>
  `;
  document.body.insertAdjacentHTML('beforeend', lightboxHTML);

  const modal = document.getElementById('lightbox-modal');
  const mainImg = document.getElementById('lightbox-main-img');
  const thumbsContainer = document.getElementById('lightbox-thumbs');
  const closeBtn = document.getElementById('close-lightbox');

  closeBtn.onclick = () => {
    modal.classList.add('hidden');
    document.body.style.overflow = 'auto';
  };

  modal.onclick = (e) => {
    if (e.target === modal) {
      modal.classList.add('hidden');
      document.body.style.overflow = 'auto';
    }
  };

  document.querySelectorAll('.image-zoom-container').forEach((gridContainer, idx) => {
    gridContainer.style.cursor = 'zoom-in';
    gridContainer.onclick = () => {
      const activeProd = getActiveProduct();
      if (!activeProd) return;
      
      thumbsContainer.innerHTML = activeProd.images.map((imgUrl, i) => `
        <div class="w-16 h-20 rounded-xl overflow-hidden cursor-pointer border-2 ${i === idx ? 'border-amber-400' : 'border-transparent'} transition-all shadow-md lightbox-thumb-item" onclick="switchLightboxImage(${i})">
          <img src="${imgUrl}" class="w-full h-full object-cover">
        </div>
      `).join('');
      
      mainImg.src = activeProd.images[idx];
      modal.classList.remove('hidden');
      document.body.style.overflow = 'hidden';
    };
  });
}

window.switchLightboxImage = function(idx) {
  const activeProd = getActiveProduct();
  if (!activeProd) return;
  
  const mainImg = document.getElementById('lightbox-main-img');
  mainImg.src = activeProd.images[idx];
  
  document.querySelectorAll('.lightbox-thumb-item').forEach((item, i) => {
    if (i === idx) {
      item.classList.add('border-amber-400');
      item.classList.remove('border-transparent');
    } else {
      item.classList.add('border-transparent');
      item.classList.remove('border-amber-400');
    }
  });
};

